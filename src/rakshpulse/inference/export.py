"""Runtime-free export of linear RakshPulse bundles (RakshPulse 4.0).

The population bundle is ``SimpleImputer(median) → StandardScaler → Ridge``. That is an affine map, so it folds
into one weight vector per target::

    y = b + Σ_i w_i · x_i,   with x_i := median_i when missing,
    w_i = coef_i / scale_i,  b = intercept − Σ_i w_i · mean_i

``export_linear`` returns this as plain data (JSON-serialisable), ``predict_exported`` evaluates it with NumPy
in float64, float32 or float16, or with int8-quantised weights, and ``to_c_header`` emits a dependency-free C99
header for a microcontroller. No ML runtime (and no ONNX dependency) is needed for the linear model.
``scripts/run_deployment_v4.py`` verifies equivalence with scikit-learn on real data.
"""

from __future__ import annotations

import numpy as np

FORMAT = "rakshpulse-linear-v1"


def _fold(pipe) -> dict:
    steps = dict(pipe.named_steps)
    imp, sc, mdl = steps.get("impute"), steps.get("scale"), steps.get("model")
    if imp is None or sc is None or mdl is None or not hasattr(mdl, "coef_"):
        raise ValueError("expected an impute -> scale -> linear model pipeline")
    coef = np.ravel(mdl.coef_).astype(float)
    scale = np.where(sc.scale_ > 0, sc.scale_, 1.0)
    w = coef / scale
    b = float(np.ravel(mdl.intercept_)[0] if np.ndim(mdl.intercept_) else mdl.intercept_) - float(w @ sc.mean_)
    return {"fill": imp.statistics_.astype(float).tolist(), "weights": w.tolist(), "bias": b}


def export_linear(bundle) -> dict:
    """Fold a linear bundle (``.features``, ``.sbp``, ``.dbp`` pipelines) into plain coefficients."""
    return {
        "format": FORMAT,
        "features": list(bundle.features),
        "targets": {"sbp": _fold(bundle.sbp), "dbp": _fold(bundle.dbp)},
    }


def quantize_int8(w: np.ndarray) -> tuple[np.ndarray, float]:
    """Symmetric per-tensor int8 quantisation; returns (int8 weights, scale)."""
    w = np.asarray(w, float)
    s = float(np.max(np.abs(w)) / 127.0) or 1.0
    return np.clip(np.round(w / s), -127, 127).astype(np.int8), s


def predict_exported(params: dict, X: np.ndarray, target: str = "sbp", precision: str = "float64") -> np.ndarray:
    """Evaluate the exported model; ``precision`` in float64 | float32 | float16 | int8 (weights only)."""
    p = params["targets"][target]
    X = np.asarray(X, float)
    fill = np.asarray(p["fill"], float)
    X = np.where(np.isfinite(X), X, fill)
    w = np.asarray(p["weights"], float)
    if precision == "int8":
        q, s = quantize_int8(w)
        return p["bias"] + (X @ q.astype(np.int32).astype(float)) * s
    dt = {"float64": np.float64, "float32": np.float32, "float16": np.float16}[precision]
    return (np.asarray(p["bias"], dt) + X.astype(dt) @ w.astype(dt)).astype(float)


def to_c_header(params: dict, name: str = "rakshpulse_bp") -> str:
    """C99 header: float32 coefficients and a ``<name>_predict(const float *x, float *sbp, float *dbp)``."""
    n = len(params["features"])

    def arr(v):
        return ", ".join(f"{x:.9g}f" for x in v)

    lines = [
        f"/* Generated by rakshpulse.inference.export ({FORMAT}). Research prototype, NOT a medical device. */",
        f"#ifndef {name.upper()}_H",
        f"#define {name.upper()}_H",
        "#include <math.h>",
        f"#define {name.upper()}_N_FEATURES {n}",
        "/* feature order: " + ", ".join(params["features"]) + " */",
    ]
    for t in ("sbp", "dbp"):
        p = params["targets"][t]
        lines += [
            f"static const float {name}_{t}_fill[{n}] = {{{arr(p['fill'])}}};",
            f"static const float {name}_{t}_w[{n}] = {{{arr(p['weights'])}}};",
            f"static const float {name}_{t}_b = {p['bias']:.9g}f;",
        ]
    lines += [
        f"static inline float {name}_dot(const float *x, const float *w, const float *fill) {{",
        "    float acc = 0.0f;",
        f"    for (int i = 0; i < {n}; ++i) acc += (isfinite(x[i]) ? x[i] : fill[i]) * w[i];",
        "    return acc;",
        "}",
        f"static inline void {name}_predict(const float *x, float *sbp, float *dbp) {{",
        f"    *sbp = {name}_sbp_b + {name}_dot(x, {name}_sbp_w, {name}_sbp_fill);",
        f"    *dbp = {name}_dbp_b + {name}_dot(x, {name}_dbp_w, {name}_dbp_fill);",
        "}",
        "#endif",
        "",
    ]
    return "\n".join(lines)
